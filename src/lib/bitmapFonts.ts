/**
 * Bitmap Font Definitions
 *
 * Provides bitmap font glyphs in three canonical sizes (3x5, 5x7, 7x9).
 * Each glyph is a boolean 2D array where true = filled pixel.
 *
 * Supported characters: A-Z (uppercase), 0-9, common punctuation, and space.
 */

// ============================================================================
// Types
// ============================================================================

/** A glyph is a 2D boolean array: rows × columns. true = filled pixel */
export type Glyph = boolean[][];

/** Map of characters to their glyph definitions */
export type GlyphMap = Record<string, Glyph>;

/** Font definition with metadata */
export interface BitmapFont {
  /** Canonical width (columns) */
  width: number;
  /** Canonical height (rows) */
  height: number;
  /** Character to glyph mapping */
  glyphs: GlyphMap;
}

/** Available font sizes */
export type FontSize = '3x5' | '5x7' | '7x9';

// ============================================================================
// Glyph Validation
// ============================================================================

/**
 * Validates that a glyph matches the expected dimensions.
 * Throws an error if dimensions don't match.
 */
function validateGlyph(char: string, glyph: Glyph, width: number, height: number): void {
  if (glyph.length !== height) {
    throw new Error(`Glyph '${char}' has ${glyph.length} rows, expected ${height}`);
  }
  for (let row = 0; row < glyph.length; row++) {
    if (glyph[row].length !== width) {
      throw new Error(`Glyph '${char}' row ${row} has ${glyph[row].length} columns, expected ${width}`);
    }
  }
}

/**
 * Creates a validated glyph map, ensuring all glyphs match dimensions.
 */
function createValidatedGlyphMap(glyphs: GlyphMap, width: number, height: number): GlyphMap {
  for (const [char, glyph] of Object.entries(glyphs)) {
    validateGlyph(char, glyph, width, height);
  }
  return glyphs;
}

// ============================================================================
// Helper: Convert string pattern to boolean array
// ============================================================================

/**
 * Converts a string pattern like "###" to boolean array [true, true, true].
 * '#' = true (filled), anything else = false (empty)
 */
function p(pattern: string): boolean[] {
  return pattern.split('').map(c => c === '#');
}

