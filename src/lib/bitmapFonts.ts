export const FONTS: Record<FontSize, BitmapFont> = {
  '3x5': {
    width: 3,
    height: 5,
    glyphs: font3x5Glyphs,
  },
  '5x7': {
    width: 5,
    height: 7,
    glyphs: font5x7Glyphs,
  },
  '7x9': {
    width: 7,
    height: 9,
    glyphs: font7x9Glyphs,
  },
};

/**
 * Gets a font by size.
 */
export function getFont(size: FontSize): BitmapFont {
  return FONTS[size];
}

/**
 * Gets a glyph for a character from a specific font.
 * Returns undefined if the character is not supported.
 */
export function getGlyph(char: string, size: FontSize): Glyph | undefined {
  const font = FONTS[size];
  return font.glyphs[char.toUpperCase()];
}

/**
 * Checks if a character is supported by the fonts.
 */
export function isCharSupported(char: string): boolean {
  return char.toUpperCase() in FONTS['3x5'].glyphs;
}

/**
 * Gets all supported characters.
 */
export function getSupportedCharacters(): string[] {
  return Object.keys(FONTS['3x5'].glyphs);
}

